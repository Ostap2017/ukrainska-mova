// Тема
(function(){
  var root=document.documentElement, btns=document.querySelectorAll('.themes button'), saved=null;
  try{saved=localStorage.getItem('theme')}catch(e){}
  function mark(t){
    var cur=t||(matchMedia('(prefers-color-scheme: dark)').matches?'dark':'light');
    btns.forEach(function(b){b.setAttribute('aria-pressed',b.dataset.t===cur)});
  }
  if(saved){root.setAttribute('data-theme',saved)}
  mark(saved);
  btns.forEach(function(b){b.addEventListener('click',function(){
    root.setAttribute('data-theme',b.dataset.t);mark(b.dataset.t);
    try{localStorage.setItem('theme',b.dataset.t)}catch(e){}
  })});
})();

